import JSZip from "jszip";

import {
  generatePythonElementProgram,
  generateTinyAdElementProgramHeader,
} from "./energy-codegen";
import { formatElementProgram, validateElementProgram, type VertexElementProgram } from "./element-program";
import { generateBlogEmbedHtml, generateBlogMarkdown } from "./experiment-publishing";

export interface ResearchBundleOptions {
  pageUrl?: string;
}

export async function buildResearchBundle(
  value: VertexElementProgram,
  options: ResearchBundleOptions = {},
): Promise<Blob> {
  const program = validateElementProgram(value);
  const archive = new JSZip();
  archive.file(`${program.id}.element-program.json`, formatElementProgram(program));
  archive.file("cpp/GeneratedElementProgram.hh", generateTinyAdElementProgramHeader(program));
  archive.file("python/generated_element_program.py", generatePythonElementProgram(program));
  if (options.pageUrl) {
    archive.file("web/blog-embed.html", generateBlogEmbedHtml(options.pageUrl, program));
    archive.file("web/blog-fallback.md", generateBlogMarkdown(options.pageUrl, program));
  }
  archive.file("README.md", `# ${program.name}

This source bundle was generated by Direction Field Lab from one shared
\`geometry-lab/element-program@1\` file.

## Files

- \`${program.id}.element-program.json\`: browser/shareable source of truth.
- \`cpp/GeneratedElementProgram.hh\`: matching TinyAD callbacks on vertices,
  connection edges, and circulation faces.
- \`python/generated_element_program.py\`: equivalent scalar energy functions.
${options.pageUrl ? "- `web/blog-embed.html`: a responsive iframe containing this exact program.\n- `web/blog-fallback.md`: a linked fallback for blogs that do not allow iframes.\n" : ""}

The generated callbacks intentionally do not hide mesh setup. Copy the header
into Direction Field Lab's \`geometry-processing-starter-kit\` or another TinyAD project,
construct the declared element ranges, and use TinyAD's scalar-function API to
assemble the global sparse gradient and Hessian. Precompute every triangle's
circulation coefficients in its vertex tangent frames.

Use the portable experiment file as the stable identity when publishing browser
and Polyscope results from the larger project.
`);
  return archive.generateAsync({ type: "blob", compression: "DEFLATE" });
}
